-- V1: начальная схема — те же таблицы, что раньше создавал Hibernate.
-- На твоей существующей базе этот файл НЕ выполняется (baseline = 1),
-- а на новой пустой базе (тесты, другой компьютер, Docker) создаёт всё с нуля.

create table app_user (
    id            bigint generated by default as identity primary key,
    username      varchar(50)  not null unique,
    password_hash varchar(255) not null
);

create table workout_session (
    id           bigint generated by default as identity primary key,
    workout_date date          not null,
    day_name     varchar(255)  not null,
    feel         integer,
    body_weight  double precision,
    note         varchar(1000),
    user_id      bigint references app_user (id)
);

create table set_entry (
    id         bigint generated by default as identity primary key,
    exercise   varchar(255) not null,
    set_number integer      not null,
    weight     double precision,
    reps       integer,
    rate       varchar(255),
    session_id bigint references workout_session (id)
);
